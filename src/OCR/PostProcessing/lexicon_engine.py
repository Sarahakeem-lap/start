# (د) بناء قاموس مخصص
# ─────────────────────────────────────────────────────────
def build_custom_lexicon(words: List[str]) -> None:
    """
    إضافة كلمات جديدة للقاموس المخصص.
    - يستقبل قائمة كلمات
    - يحفظها في custom_lexicon.json
    - يدمجها تلقائياً مع القاموس الأساسي في المرة القادمة
    """
    if not words:
        return

    # تحميل القاموس المخصص الموجود
    custom_words = set()
    if CUSTOM_LEXICON_PATH.exists():
        try:
            data = json.loads(CUSTOM_LEXICON_PATH.read_text(encoding="utf-8"))
            custom_words.update(data.get("words", []))
        except Exception:
            pass

    # إضافة الكلمات الجديدة
    new_words = [w.strip() for w in words if w.strip()]
    custom_words.update(new_words)
    custom_words.difference_update(FULL_LEXICON)  # لا نكرر ما هو موجود

    # حفظ
    CUSTOM_LEXICON_PATH.write_text(
        json.dumps({"words": sorted(custom_words)}, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    # دمج مع القاموس الأساسي
    FULL_LEXICON.update(custom_words)
    for w in new_words:
        wl = w.lower()
        if wl not in LEXICON_LOWERCASE:
            LEXICON_LOWERCASE[wl] = w


def _load_custom_lexicon() -> None:
    """تحميل القاموس المخصص عند استيراد الموديول."""
    if CUSTOM_LEXICON_PATH.exists():
        try:
            data = json.loads(CUSTOM_LEXICON_PATH.read_text(encoding="utf-8"))
            FULL_LEXICON.update(data.get("words", []))
        except Exception:
            pass


# تحميل القاموس المخصص تلقائياً
_load_custom_lexicon()


