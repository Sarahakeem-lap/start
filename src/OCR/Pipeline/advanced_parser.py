# ─────────────────────────────────────────────────────────
# (أ) تصحيح المصطلحات الأكاديمية
# ─────────────────────────────────────────────────────────
def correct_academic_terms(text: str) -> str:
    """
    تصحيح المصطلحات الأكاديمية من القاموس.
    يدعم الكلمات المركبة (متعددة الكلمات) والكلمات المفردة.
    """
    if not text:
        return ""

    # 1. تصحيح العبارات المركبة (متعددة الكلمات) أولاً
    # نرتب keys طولياً (الأطول أولاً) لتجنب التطابق الجزئي
    multi_word = sorted(
        [(k, v) for k, v in ACADEMIC_TERMS.items() if ' ' in k.strip()],
        key=lambda x: -len(x[0])
    )
    for wrong, correct in multi_word:
        text = text.replace(wrong, correct)

    # 2. تصحيح الكلمات المفردة عبر regex
    def _replace_match(match):
        """استبدال الكلمة بقيمتها في القاموس."""
        word = match.group(0)
        # تنظيف الكلمة من الرموز غير العربية
        clean = re.sub(r"[^\u0600-\u06FF\s]", "", word)
        # البحث في القاموس
        if clean in ACADEMIC_TERMS:
            return word.replace(clean, ACADEMIC_TERMS[clean])
        return word

    # تطبيق التصحيح على كل الكلمات العربية
    return re.sub(r"[\u0600-\u06FF]{2,}", _replace_match, text)


